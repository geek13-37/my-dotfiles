#!/usr/bin/env python3
"""Build boxshell's app-theming config out of Noctalia's templates.

boxshell runs `noctalia theme <wallpaper> -c templates.toml` on every
wallpaper change. This collects the templates Noctalia had enabled (built-in
ones from /usr/share/noctalia, community ones from Noctalia's download cache)
plus the user templates from ~/.config/noctalia/config.toml (SDDM colours)
into one file with absolute paths, keeping only apps that are installed
(their config folder exists). Rerun it after installing a new app.
"""
import json
import os
import tomllib
from pathlib import Path

HOME = Path.home()
BUILTIN_DIR = Path("/usr/share/noctalia/assets/templates")
COMMUNITY_DIR = HOME / ".local/state/noctalia/community-templates"
USER_CONFIG = HOME / ".config/noctalia/config.toml"
OUT = Path(__file__).with_name("templates.toml")

BUILTIN = ["alacritty", "btop", "cava", "gtk3", "gtk4", "qt"]
# always written: GTK/Qt apps read these without a config folder of their own
ALWAYS = {"gtk3", "gtk4", "qt", "sddm"}
COMMUNITY = ["spicetify", "discord", "telegram", "gimp", "vscode", "zed", "steam",
             "fastfetch", "obs", "yazi", "claude-code", "opencode"]


def expand(path: str) -> Path:
    path = path.replace("$XDG_CONFIG_HOME", str(HOME / ".config"))
    return Path(os.path.expanduser(path))


def app_root(output: Path) -> Path:
    """~/.config/<app>, ~/.var/app/<flatpak id> or ~/<.app>: the folder that
    exists once the app is installed."""
    parts = output.relative_to(HOME).parts
    if parts[0] == ".config":
        return HOME.joinpath(*parts[:2])
    if parts[:2] == (".var", "app"):
        return HOME.joinpath(*parts[:3])
    return HOME / parts[0]


def installed(name: str, entry: dict) -> bool:
    if name in ALWAYS:
        return True
    if "requires_path" in entry:
        return expand(entry["requires_path"]).exists()
    outputs = entry["output_path"]
    outputs = outputs if isinstance(outputs, list) else [outputs]
    return all(app_root(expand(o)).exists() for o in outputs)


def absolute(entry: dict, base: Path) -> dict:
    entry = dict(entry)
    entry.pop("undo_hook", None)
    entry["input_path"] = str((base / entry["input_path"]).resolve())
    for key in ("post_hook",):
        if key in entry:
            entry[key] = entry[key].replace("{{ config_dir }}", str(base))
    return entry


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    return json.dumps(value)


templates = {}
builtin = tomllib.loads((BUILTIN_DIR / "builtin.toml").read_text())["templates"]
for name in BUILTIN:
    templates[name] = absolute(builtin[name], BUILTIN_DIR)
for cid in COMMUNITY:
    base = COMMUNITY_DIR / cid
    # Noctalia downloads these on its first run with the template enabled
    if not (base / "template.toml").exists():
        continue
    for name, entry in tomllib.loads((base / "template.toml").read_text())["templates"].items():
        templates[name] = absolute(entry, base)
user = {} if not USER_CONFIG.exists() else tomllib.loads(USER_CONFIG.read_text()).get("theme", {}).get("templates", {}).get("user", {})
for name, entry in user.items():
    entry = dict(entry, input_path=str(expand(entry["input_path"])))
    templates[name] = absolute(entry, USER_CONFIG.parent)

lines = ["# Generated by gen-templates.py; rerun it instead of editing.", ""]
for name, entry in templates.items():
    if not installed(name, entry):
        continue
    lines.append(f"[templates.{json.dumps(name)}]")
    lines += [f"{k} = {toml_value(v)}" for k, v in entry.items()]
    lines.append("")
OUT.write_text("\n".join(lines))
print("\n".join(l[11:-1] for l in lines if l.startswith("[templates.")))
